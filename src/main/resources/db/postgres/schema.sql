CREATE TABLE IF NOT EXISTS vets (
                                    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    first_name TEXT,
                                    last_name  TEXT
);
CREATE INDEX ON vets (last_name);

CREATE TABLE IF NOT EXISTS specialties (
                                           id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           name TEXT
);
CREATE INDEX ON specialties (name);

CREATE TABLE IF NOT EXISTS vet_specialties (
                                               vet_id       INT NOT NULL REFERENCES vets (id),
                                               specialty_id INT NOT NULL REFERENCES specialties (id),
                                               UNIQUE (vet_id, specialty_id)
);

CREATE TABLE IF NOT EXISTS types (
                                     id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     name TEXT
);
CREATE INDEX ON types (name);

CREATE TABLE IF NOT EXISTS owners (
                                      id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      first_name TEXT,
                                      last_name  TEXT,
                                      address    TEXT,
                                      city       TEXT,
                                      telephone  TEXT
);
CREATE INDEX ON owners (last_name);

CREATE TABLE IF NOT EXISTS pets (
                                    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    name       TEXT,
                                    birth_date DATE,
                                    type_id    INT NOT NULL REFERENCES types (id),
                                    owner_id   INT REFERENCES owners (id)
);
CREATE INDEX ON pets (name);
CREATE INDEX ON pets (owner_id);

CREATE TABLE IF NOT EXISTS visits (
                                      id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      pet_id      INT REFERENCES pets (id),
                                      visit_date  DATE,
                                      description TEXT
);
CREATE INDEX ON visits (pet_id);

CREATE TABLE IF NOT EXISTS users (
  username VARCHAR(20) NOT NULL ,
  password VARCHAR(60) NOT NULL ,
  enabled boolean NOT NULL DEFAULT true ,
  CONSTRAINT pk_users PRIMARY KEY (username)
);

CREATE TABLE IF NOT EXISTS roles (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(20) NOT NULL,
  role varchar(20) NOT NULL,
  FOREIGN KEY (username) REFERENCES users (username),
  CONSTRAINT uni_username_role UNIQUE (role, username)
);

CREATE TABLE IF NOT EXISTS owner_user_links (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INT NOT NULL REFERENCES owners (id) ON DELETE CASCADE,
  username VARCHAR(20) NOT NULL REFERENCES users (username) ON DELETE CASCADE,
  verified BOOLEAN NOT NULL DEFAULT true,
  CONSTRAINT uni_owner_user_links_username UNIQUE (username),
  CONSTRAINT uni_owner_user_links_owner_id UNIQUE (owner_id)
);

CREATE TABLE IF NOT EXISTS vet_availability_slots (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vet_id INT NOT NULL REFERENCES vets (id) ON DELETE CASCADE,
  start_date_time TIMESTAMPTZ NOT NULL,
  end_date_time TIMESTAMPTZ NOT NULL
);
CREATE INDEX ON vet_availability_slots (vet_id);

CREATE TABLE IF NOT EXISTS video_consultations (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INT NOT NULL REFERENCES owners (id) ON DELETE CASCADE,
  vet_id INT NOT NULL REFERENCES vets (id) ON DELETE CASCADE,
  start_date_time TIMESTAMPTZ NOT NULL,
  end_date_time TIMESTAMPTZ NOT NULL,
  triage_level VARCHAR(16) NOT NULL,
  triage_priority VARCHAR(16) NOT NULL,
  status VARCHAR(16) NOT NULL,
  reason VARCHAR(500) NOT NULL,
  created_at TIMESTAMP NOT NULL
);
CREATE INDEX ON video_consultations (owner_id);
CREATE INDEX ON video_consultations (vet_id, start_date_time, end_date_time);
